#!/usr/bin/env node

/**
 * Verification and backfill script for match.next_match_id.
 *
 * This script validates that knockout match advancement links are correct,
 * and optionally populates any missing next_match_id values.
 *
 * The 2026 World Cup knockout structure is:
 *   Round of 32 (matches 73-88) -> Round of 16 (matches 89-96)
 *   Round of 16 (matches 89-96) -> Quarter-finals (matches 97-100)
 *   Quarter-finals (matches 97-100) -> Semi-finals (matches 101-102)
 *   Semi-finals (matches 101-102) -> Final (match 104)
 *   Semi-final losers -> Third place (match 103)
 *
 * Usage:
 *   node scripts/backfill-next-match-id.mjs              # Dry-run: validate only
 *   node scripts/backfill-next-match-id.mjs --write       # Write missing values
 *   node scripts/backfill-next-match-id.mjs --sql-only    # Print SQL for missing values
 */

import { createClient } from "@supabase/supabase-js";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

// ---------------------------------------------------------------------------
// Tournament structure: maps each knockout match to the match the winner
// advances to. Terminal matches (final, third_place) have no next match.
// ---------------------------------------------------------------------------

const NEXT_MATCH_MAP = new Map([
  // Round of 32 -> Round of 16
  [73, 89], [74, 89],
  [75, 90], [76, 90],
  [77, 91], [78, 91],
  [79, 92], [80, 92],
  [81, 93], [82, 93],
  [83, 94], [84, 94],
  [85, 95], [86, 95],
  [87, 96], [88, 96],
  // Round of 16 -> Quarter-finals
  [89, 97], [90, 97],
  [91, 98], [92, 98],
  [93, 99], [94, 99],
  [95, 100], [96, 100],
  // Quarter-finals -> Semi-finals
  [97, 101], [98, 101],
  [99, 102], [100, 102],
  // Semi-finals -> Final / Third place
  [101, 104], [102, 104],
  // Third place and Final have no next match (correctly null)
]);

const argv = process.argv.slice(2);
const args = new Set(argv);
const writeMode = args.has("--write");
const sqlOnly = args.has("--sql-only");

if (writeMode && sqlOnly) {
  console.error("Choose either --write or --sql-only, not both.");
  process.exit(1);
}

loadEnvFile(".env.local");
loadEnvFile(".env");

const supabase = createSupabaseClient();

try {
  const { data: matches, error } = await supabase
    .from("match")
    .select("id, round, next_match_id, phase")
    .eq("phase", "knockout")
    .is("group_id", null)
    .order("id", { ascending: true });

  if (error) {
    throw new Error(`Could not read knockout matches: ${error.message}`);
  }

  if (!matches || matches.length === 0) {
    console.log("No knockout matches found in the database.");
    process.exit(0);
  }

  // ---------------------------------------------------------------------------
  // Validate existing values
  // ---------------------------------------------------------------------------

  const results = [];
  let correctCount = 0;
  let missingCount = 0;
  let mismatchCount = 0;

  for (const match of matches) {
    const expected = NEXT_MATCH_MAP.get(match.id) ?? null;
    const actual = match.next_match_id;

    if (actual === expected) {
      correctCount++;
      results.push({ id: match.id, round: match.round, status: "ok", actual, expected });
    } else if (actual === null && expected !== null) {
      missingCount++;
      results.push({ id: match.id, round: match.round, status: "missing", actual, expected });
    } else if (actual !== expected) {
      mismatchCount++;
      results.push({ id: match.id, round: match.round, status: "mismatch", actual, expected });
    }
  }

  console.log(`\nnext_match_id validation results:`);
  console.log(`  Correct:   ${correctCount}`);
  console.log(`  Missing:   ${missingCount}`);
  console.log(`  Mismatch:  ${mismatchCount}`);
  console.log(`  Total:     ${results.length}\n`);

  const issues = results.filter((r) => r.status !== "ok");

  if (issues.length > 0) {
    console.log("Issues found:");
    for (const issue of issues) {
      const detail = issue.status === "missing"
        ? `expected ${issue.expected} but is null`
        : `expected ${issue.expected} but found ${issue.actual}`;
      console.log(`  Match ${issue.id} (${issue.round}): ${detail}`);
    }

    // ---------------------------------------------------------------------------
    // Fix missing values
    // ---------------------------------------------------------------------------

    const missingIssues = issues.filter((r) => r.status === "missing");

    if (missingIssues.length > 0) {
      if (sqlOnly) {
        console.log("\nSQL to fix missing next_match_id values:");
        console.log("-- Generated by backfill-next-match-id.mjs");
        for (const issue of missingIssues) {
          console.log(
            `UPDATE public.match SET next_match_id = ${issue.expected} WHERE id = ${issue.id}; -- ${issue.round}`,
          );
        }
      } else if (writeMode) {
        console.log(`\nWriting ${missingIssues.length} missing next_match_id value(s)...`);

        for (const issue of missingIssues) {
          const { error: updateError } = await supabase
            .from("match")
            .update({ next_match_id: issue.expected })
            .eq("id", issue.id);

          if (updateError) {
            console.error(`  FAILED to update match ${issue.id}: ${updateError.message}`);
          } else {
            console.log(`  Updated match ${issue.id} (${issue.round}): next_match_id -> ${issue.expected}`);
          }
        }
      } else {
        console.log("\nRun with --write to populate missing values, or --sql-only to print SQL.");
      }
    }

    const mismatchIssues = issues.filter((r) => r.status === "mismatch");
    if (mismatchIssues.length > 0) {
      console.log("\n⚠ Mismatching values require manual review before overwriting:");
      for (const issue of mismatchIssues) {
        console.log(
          `  Match ${issue.id} (${issue.round}): DB has ${issue.actual}, expected ${issue.expected}`,
        );
      }
    }
  } else {
    console.log("All knockout match next_match_id values are correct.");
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function loadEnvFile(fileName) {
  const path = resolve(process.cwd(), fileName);

  if (!existsSync(path)) return;

  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    const separator = trimmed.indexOf("=");
    if (separator === -1) continue;

    const key = trimmed.slice(0, separator).trim();
    const rawValue = trimmed.slice(separator + 1).trim();

    if (!key || process.env[key]) continue;

    process.env[key] = rawValue.replace(/^['"]|['"]$/g, "");
  }
}

function createSupabaseClient() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? process.env.SUPABASE_URL;
  const key =
    process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ??
    process.env.SUPABASE_COUNTRY_IMPORT_KEY ??
    process.env.SUPABASE_SECRET_KEY ??
    process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!url) {
    throw new Error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_URL.");
  }

  if (!key) {
    throw new Error(
      "Missing Supabase key. Set NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, SUPABASE_COUNTRY_IMPORT_KEY, SUPABASE_SECRET_KEY, or SUPABASE_SERVICE_ROLE_KEY.",
    );
  }

  return createClient(url, key, {
    auth: {
      autoRefreshToken: false,
      detectSessionInUrl: false,
      persistSession: false,
    },
    global: {
      headers: {
        "X-Client-Info": "wc26-backfill-next-match-id",
      },
    },
  });
}